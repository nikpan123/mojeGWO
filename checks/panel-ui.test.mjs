test('panel przełącza TEST i PROD, zachowuje funkcje i działa na telefonie',async()=>{
 const server=await createApplication();await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const origin='http://127.0.0.1:'+server.address().port;let browser;
 try{
  const installed=await fs.access(chromium.executablePath()).then(()=>true,()=>false);
  browser=await chromium.launch({headless:true,...(installed?{}:{channel:'msedge'})});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  const arrowResponses=[],policyErrors=[];
  page.on('response',response=>{if(/select-chevron-(light|dark)\.svg$/.test(response.url()))arrowResponses.push({url:response.url(),status:response.status()});});
  page.on('console',message=>{if(message.type()==='error'&&/Content Security Policy/.test(message.text()))policyErrors.push(message.text());});
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(origin+'/test/');await expect(page.locator('#environment-choice [aria-current="page"]')).toHaveText('TEST');
  await page.locator('nav a[href="#run"]').click();
  await expect.poll(()=>arrowResponses.some(response=>response.url.endsWith('select-chevron-light.svg')&&response.status===200)).toBe(true);
  await page.locator('[data-theme-value="dark"]').click();await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
  await expect.poll(()=>arrowResponses.some(response=>response.url.endsWith('select-chevron-dark.svg')&&response.status===200)).toBe(true);
  await page.reload();await expect(page.locator('[data-theme-value="dark"]')).toHaveAttribute('aria-pressed','true');
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
  await page.locator('[data-theme-value="light"]').click();await expect(page.locator('html')).toHaveAttribute('data-theme','light');
  await expect(page.locator('#teacher-choice option')).toHaveCount(1);
  await page.locator('nav a[href="#load"]').click();await expect(page.locator('#load-form')).toBeVisible();
  await expect(page.locator('#load-run')).toBeDisabled();
  await page.locator('#environment-choice a').filter({hasText:'PROD'}).click();await page.waitForURL('**/prod/');
  await expect(page.locator('#environment-choice [aria-current="page"]')).toHaveText('PROD');
  await expect(page.locator('#teacher-choice option')).toHaveCount(1);assert.equal(await page.locator('#load-form').count(),0);
  await page.locator('nav a[href="#run"]').click();await expect(page.locator('#run')).toBeDisabled();
  assert.equal(await page.locator('#suite-choice option[value="websites"]').count(),1);
  async function checkWorksheetAddress(expected){
   await page.locator('nav a[href="#teachers"]').click();
   await page.locator('[data-action="add-resource"]').click();
   const material=page.locator('#material-form'),entry=material.locator('[name="entryURL"]');
   await material.locator('[name="kind"]').selectOption('aplikacja');
   await material.locator('[name="adapter"]').selectOption('worksheets');
   await expect(entry).toHaveValue(expected);await expect(entry).toHaveAttribute('required','');
   await expect(entry.locator('..')).toContainText('wymagany');
   await entry.fill('https://example.com/pozostaw');
   await material.locator('[name="adapter"]').selectOption('access');await expect(entry).not.toHaveAttribute('required','');
   await material.locator('[name="adapter"]').selectOption('worksheets');await expect(entry).toHaveValue('https://example.com/pozostaw');
   await material.locator('[data-close-dialog]').click();
  }
  await checkWorksheetAddress('https://kartypracy.apps.gwo.pl/25/EW/1');
  await page.locator('nav a[href="#scenarios"]').click();
  await expect(page.locator('.scenario-group')).toHaveCount(4);
  await expect(page.locator('.scenario-group[data-group="functional"] .scenario-card')).toHaveCount(5);
  await expect(page.locator('.scenario-group[data-group="functional"]')).toContainText('Multipodręcznik — otwarcie i zmiana stron');
  await expect(page.locator('#environment-choice select,#theme-mode select')).toHaveCount(0);
  await expect(page.locator('#environment-choice a')).toHaveCount(2);
  await expect(page.locator('#theme-mode button')).toHaveCount(3);
  await page.locator('#scenario-filter').selectOption('services');await expect(page.locator('.scenario-card')).toHaveCount(9);
  await page.locator('#scenario-search').fill('cache');await expect(page.locator('.scenario-card')).toHaveCount(3);
  await page.locator('.scenario-details summary').first().click();await expect(page.locator('.scenario-details[open]')).toHaveCount(1);
  await page.locator('#scenario-search').fill('brak-dopasowania-123');await expect(page.locator('.scenario-empty')).toBeVisible();
  const dir=path.join(root,'.health','qa');await fs.mkdir(dir,{recursive:true});
  await page.screenshot({path:path.join(dir,'prod-panel.png'),fullPage:true});
  await page.locator('#environment-choice a').filter({hasText:'TEST'}).click();await page.waitForURL('**/test/');
  await expect(page.locator('#teacher-choice option')).toHaveCount(1);
  assert.equal(await page.locator('nav a[href="#schedule"]').count(),0);
  await checkWorksheetAddress('https://kartypracy.apps.gwotest.pl/25/EW/1');
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(dir,'test-mobile.png'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(errors,[]);
  assert.deepEqual(policyErrors,[]);
 }finally{await browser?.close();await new Promise(resolve=>server.close(resolve));}
});

test('dziennik wyróżnia wyniki, filtruje błędy i czyści tylko wpisy',async()=>{
 const server=await createApplication();await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const origin='http://127.0.0.1:'+server.address().port;let browser;
 try{
  const state=await(await fetch(origin+'/prod/api/state')).json();
  state.schedule.events=[{at:'2026-11-27T06:30:00Z',type:'PASS',suite:'functional',message:'Zakończono zestaw.',report:'/report/aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa/',counts:{passed:5,failed:0}},{at:'2026-11-27T06:29:00Z',type:'FAIL',suite:'websites',message:'Zakończono zestaw.',counts:{passed:2,failed:1}},{at:'2026-11-27T06:28:00Z',type:'START',message:'Rozpoczęto cykl.'}];
  state.schedule.events[0].profileLabel='Nauczyciel przykładowy';state.schedule.events[0].materials=[{id:'demo',title:'Matematyka. Klasa 5',kind:'multipodrecznik',checkMode:'functional'}];
  state.schedule.enabled=true;state.schedule.events[2].message='Przykładowe długie zdarzenie. '.repeat(250);
  state.profiles.teachers[0].resources=[{id:'a',title:'Matematyka. Klasa 5',kind:'multipodrecznik'},{id:'b',title:'Geografia. Klasa 6',kind:'multipodrecznik'}];
  state.profiles.teachers[0].catalog=[{id:'1',title:'Matematyka. Klasa 5',kind:'multipodrecznik',teacher:true},{id:'2',title:'W świecie geografii',kind:'multipodrecznik',teacher:true},{id:'3',title:'Kompozytor',kind:'aplikacja',teacher:true}];
  const installed=await fs.access(chromium.executablePath()).then(()=>true,()=>false);
  browser=await chromium.launch({headless:true,...(installed?{}:{channel:'msedge'})});const page=await browser.newPage();let clears=0;
  await page.route('**/prod/api/state',route=>route.fulfill({json:state}));
  await page.route('**/prod/api/schedule',route=>{const body=route.request().postDataJSON();assert.equal(body.enabled,false);assert.ok(!Object.hasOwn(body,'events'));assert.ok(route.request().postData().length<1024);state.schedule.enabled=false;state.schedule.revision++;return route.fulfill({json:{schedule:state.schedule}});});
  await page.route('**/prod/api/schedule/events/clear',route=>{assert.equal(route.request().method(),'POST');clears++;state.schedule.events=[];return route.fulfill({json:{schedule:state.schedule}});});
  await page.goto(origin+'/prod/#schedule');
  await expect(page.locator('#schedule-form legend').first()).toHaveText('1. Wybierz testy do uruchamiania');
  await expect(page.locator('#schedule-saved-scope')).toContainText('Zapisany zakres:');
  await page.locator('#schedule-form input[name="functional"]').uncheck();await expect(page.locator('#schedule-teacher-step')).toBeHidden();
  await expect(page.locator('#schedule-selection')).toContainText('3 kontrole bez logowania');
  await page.locator('#schedule-form input[name="websites"]').uncheck();await expect(page.locator('#schedule-selection')).toContainText('Nie wybrano testów');
  await expect(page.locator('#schedule-form button[type="submit"]')).toBeDisabled();
  await page.locator('#schedule-form input[name="functional"]').check();await expect(page.locator('#schedule-teacher-step')).toBeVisible();
  await page.locator('#schedule-form input[name="websites"]').check();
  await expect(page.locator('.schedule-event')).toHaveCount(3);
  await expect(page.locator('.schedule-materials')).toContainText('Matematyka. Klasa 5');
  await expect(page.locator('.schedule-materials')).toContainText('dostęp i działanie');
  await expect(page.locator('.schedule-event--pass')).toContainText('Nauczyciel przykładowy');
  assert.equal(await page.locator('.schedule-event--pass').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(240, 250, 243)');
  assert.equal(await page.locator('.schedule-event--fail').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(255, 243, 243)');
  await expect(page.locator('.schedule-event--pass a')).toHaveAttribute('href','/prod/report/aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa/');
  await page.locator('#schedule-disable').click();await expect(page.locator('#schedule-status')).toHaveText('Harmonogram wyłączony');
  await page.locator('#schedule-event-filter').selectOption('failures');await expect(page.locator('.schedule-event')).toHaveCount(1);
  const passedTile=page.locator('[data-event-filter="passes"]'),failedTile=page.locator('[data-event-filter="failures"]'),allTile=page.locator('[data-event-filter="all"]');
  await page.locator('[data-theme-value="dark"]').click();
  for(const [tile,color] of [[passedTile,'rgb(165, 226, 188)'],[failedTile,'rgb(255, 189, 197)'],[allTile,'rgb(198, 211, 230)']]){
   assert.equal(await tile.evaluate(el=>getComputedStyle(el).color),color);
   assert.equal(await tile.locator('strong').evaluate(el=>getComputedStyle(el).color),color);
   assert.equal(await tile.locator('span').evaluate(el=>getComputedStyle(el).color),color);
  }
  await expect(failedTile).toHaveAttribute('aria-pressed','true');
  await passedTile.click();await expect(page.locator('.schedule-event')).toHaveCount(1);await expect(page.locator('.schedule-event--pass')).toHaveCount(1);
  await expect(page.locator('#schedule-event-filter')).toHaveValue('passes');await expect(passedTile).toHaveAttribute('aria-pressed','true');
  await page.evaluate(()=>window.refreshMojeGwo());await expect(passedTile).toHaveAttribute('aria-pressed','true');await expect(page.locator('.schedule-event--pass')).toHaveCount(1);
  await failedTile.focus();await page.keyboard.press('Enter');await expect(page.locator('.schedule-event--fail')).toHaveCount(1);await expect(passedTile).toHaveAttribute('aria-pressed','false');
  await allTile.click();await expect(page.locator('.schedule-event')).toHaveCount(3);await expect(allTile).toHaveAttribute('aria-pressed','true');
  await page.locator('#schedule-event-filter').selectOption('results');await expect(page.locator('.schedule-event')).toHaveCount(2);await expect(allTile).toHaveAttribute('aria-pressed','false');
  await page.locator('#schedule-form input[name="intervalMinutes"]').fill('45');
  await page.locator('#schedule-clear-events').click();await expect(page.locator('.schedule-event')).toHaveCount(0);
  await expect(page.locator('#schedule-events-message')).toContainText('Raporty i ustawienia zostały zachowane');
  await expect(page.locator('#schedule-clear-events')).toBeDisabled();
  await expect(page.locator('#schedule-form input[name="intervalMinutes"]')).toHaveValue('45');assert.equal(clears,1);
  await page.locator('nav a[href="#teachers"]').click();
  await page.locator('[data-material-search="assigned"]').fill('GEOGRAFIA');await expect(page.locator('[data-material-row="assigned"]:visible')).toHaveCount(1);
  await expect(page.locator('[data-material-row="catalog"]:visible')).toHaveCount(3);
  await page.locator('[data-material-search="catalog"]').fill('swiecie');await expect(page.locator('[data-material-row="catalog"]:visible')).toHaveCount(1);
  await page.locator('[data-material-search="assigned"]').fill('brak-dopasowania');await expect(page.locator('[data-material-empty="assigned"]')).toBeVisible();
  await page.locator('[data-material-search="assigned"]').fill('');await expect(page.locator('[data-material-row="assigned"]:visible')).toHaveCount(2);
  await page.evaluate(()=>window.refreshMojeGwo());await expect(page.locator('[data-material-search="catalog"]')).toHaveValue('swiecie');
  assert.equal(state.profiles.teachers[0].resources.length,2);
 }finally{await browser?.close();await new Promise(resolve=>server.close(resolve));}
});
